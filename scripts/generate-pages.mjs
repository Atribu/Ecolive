const extraAssets = JSON.parse(await readFile("extra-assets.json", "utf8"));
const visuals = Object.fromEntries(
  extraAssets.assets.map((item) => [
    item.filename.split("/").pop().replace(".webp", ""),
    {
      image: item.filename,
      alt: item.alt_tr,
      ...item.dimensions,
      position: item.suggested_object_position,
    },
  ]),
);
const featureVisuals = {
  yasam: [visuals["shared-lounge"], visuals["botanic-workshop"]],
  saglik: [visuals["rehabilitation-interior"], visuals["wellness-treatment"]],
  egitim: [visuals["learning-greenhouse"], visuals["botanic-workshop"]],
  uretim: [visuals["learning-greenhouse"], visuals["botanic-workshop"]],
  doga: [visuals["lakeside-landscape"], visuals["botanic-workshop"]],
  dongu: [visuals["learning-greenhouse"], visuals["lakeside-landscape"]],
};

const esc = (value) =>
  String(value)
    .replaceAll("&", "&amp;")
    .replaceAll('"', "&quot;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;");
const home = enhanceResponsiveImages((await readFile("index.html", "utf8")).replace(/<!-- spatial-gallery:start -->[\s\S]*?<!-- spatial-gallery:end -->/, `<!-- spatial-gallery:start -->${renderSpatialGallery()}<!-- spatial-gallery:end -->`).replace(/<!-- campus-explorer:start -->[\s\S]*?<!-- campus-explorer:end -->/, `<!-- campus-explorer:start -->${renderCampusExplorer()}<!-- campus-explorer:end -->`).replace(/<!-- day-rhythm:start -->[\s\S]*?<!-- day-rhythm:end -->/, `<!-- day-rhythm:start -->${renderDayRhythm()}<!-- day-rhythm:end -->`).replace(/<!-- immersive-journey:start -->[\s\S]*?<!-- immersive-journey:end -->/, `<!-- immersive-journey:start -->${renderImmersiveJourney()}<!-- immersive-journey:end -->`));
await writeFile("index.html", home);
await writeFile(
  "focus-data.js",
  `// Generated by scripts/generate-pages.mjs; edit the content modules instead.\nexport const focusAreas = ${JSON.stringify(
    focusAreas.map(({ id, title, image, alt, description }) => ({
      id,
      title,
      alt,
      description,
      href: `/${pageDetails[id].slug}/`,
      ...responsiveImage(
        image,
        ["saglik", "egitim"].includes(id)
          ? "(max-width: 760px) 1300px, 2400px"
          : "(max-width: 760px) max(100vw, 760px), max(62vw, 1360px)",
      ),
    })),
    null,
    2,
  )};\n`,
);
await writeFile("scene-images.js", `// Generated from the page openings.
export const sceneImages = ${JSON.stringify([
  { href: "/", ...responsiveImage("assets/video/home-poster.webp", "(max-width:760px) 100vw, 50vw"), alt: "ECOLIVE yaşam alanlarının proje görselleştirmesi" },
  ...Object.entries(sceneHeroes).map(([slug, scene]) => ({ href: `/${slug}/`, ...responsiveImage(scene.image, "(max-width:760px) 100vw, 50vw"), alt: scene.alt })),
], null, 2)};\n`);
const header = home.match(/<header[\s\S]*?<\/header>/)[0];
const menu = home.match(/<dialog id="navigation"[\s\S]*?<\/dialog>/)[0];
const footer = home.match(/<footer[\s\S]*?<\/footer>/)[0];
const mapDialog = await readFile("partials/map-dialog.html", "utf8");
const asset = (file) => `/${file}`;
const href = (id) => `/${pageDetails[id].slug}/`;
const title = (italic, upper, tag = "h1") =>
  `<${tag} class="page-title"><em>${esc(italic)}</em><span>${esc(upper)}</span></${tag}>`;
const photo = (area, cls = "", eager = false) =>
  `<div class="page-photo ${cls}" data-area="${area.id}"><img sizes="${["saglik", "egitim"].includes(area.id) ? (eager ? "2050px" : "1360px") : "(max-width: 760px) max(100vw, 800px), 100vw"}" src="${asset(area.image)}" alt="${esc(area.alt)}" ${eager ? 'fetchpriority="high"' : 'loading="lazy"'} /></div>`;
const breadcrumb = (label) =>
  `<nav class="breadcrumb" aria-label="Sayfa yolu"><a href="/">Ana sayfa</a><span aria-hidden="true">/</span><span aria-current="page">${esc(label)}</span></nav>`;
const chapter = (item, index) =>
  `<article class="chapter" id="bolum-${index + 1}"><span class="chapter-number">0${index + 1}</span><div><h3>${esc(item.title)}</h3><p>${esc(item.text)}</p></div></article>`;
const intro = (p) =>
  `<section class="page-intro" data-surface-art id="yaklasim"><div><span class="micro">${esc(p.introLabel)}</span><h2>${esc(p.introTitle)}</h2></div><p>${esc(p.introText)}</p></section>`;
const quote = (p) =>
  `<section class="page-quote" data-surface-art><span class="micro">ECOLIVE YAKLAŞIMI</span><p><em>${esc(p.quote)}</em></p></section>`;
const related = (ids) =>
  `<section class="related"><div class="related-heading"><span class="micro">KEŞFETMEYE DEVAM EDİN</span><h2>Birbirini tamamlayan <em>yaşam alanları.</em></h2></div><div class="related-grid">${ids
    .map((id) => {
      const a = focusAreas.find((a) => a.id === id);
      return `<a class="related-card" href="${href(id)}">${photo(a)}<div><span class="micro">ECOLIVE’I KEŞFEDİN</span><h3>${esc(a.title)}</h3><span class="related-arrow" aria-hidden="true">↗</span></div></a>`;
    })
    .join("")}</div></section>`;

